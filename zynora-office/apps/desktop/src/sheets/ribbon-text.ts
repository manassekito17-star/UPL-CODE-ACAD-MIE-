export type RibbonText = (key: RibbonKey, vars?: Record<string, string | number>) => string;

export function ribbonText(language: Language): RibbonText {
  const dict: Record<RibbonKey, string> = language === "fr" ? fr : en;
  return (key, vars) => dict[key].replace(/\{(\w+)\}/g, (m, name: string) => (vars && name in vars ? String(vars[name]) : m));
}

