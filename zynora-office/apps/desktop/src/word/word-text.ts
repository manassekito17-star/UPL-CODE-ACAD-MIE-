export type WordText = (key: WordKey, vars?: Record<string, string | number>) => string;
export type { WordKey };

export function wordText(language: Language): WordText {
  const dict: Record<WordKey, string> = language === "fr" ? fr : en;
  return (key, vars) => dict[key].replace(/\{(\w+)\}/g, (m, name: string) => (vars && name in vars ? String(vars[name]) : m));
}

