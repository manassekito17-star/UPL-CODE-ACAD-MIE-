const DOC = (body: string, title = "Exercice", head = "") =>
  `<!DOCTYPE html>\n<html lang="fr">\n<head>\n  <meta charset="utf-8">\n  <title>${title}</title>${head ? `\n  ${head}` : ""}\n</head>\n<body>\n${body}\n</body>\n</html>`;

const html = (input: ExInput) => makeExercise({ language: "html", courseSlug: "html" }, input);

/** Exercice CSS : la page index.html est fournie, l'étudiant écrit style.css. */
const css = (input: ExInput & { page: string }) => {
  const { page, ...rest } = input;
  return {
    ...makeExercise({ language: "css", courseSlug: "css" }, rest),
    starterFiles: [
      { name: "index.html", content: DOC(page, "Exercice CSS", '<link rel="stylesheet" href="style.css">') },
      { name: "style.css", content: input.starterCode ?? "/* Écrivez vos règles ici */\n" },
    ],
    activeFile: "style.css",
  };
};

